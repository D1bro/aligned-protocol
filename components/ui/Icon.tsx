export type IconName = keyof typeof PATHS;

// Each life area's icon, by its sort_order (as AREA_SHORT_NAMES in lib/audit-guides.ts).
export const AREA_ICONS: Record<number, IconName> = {
  1: "heart", 2: "bulb", 3: "star", 4: "users", 5: "briefcase",
  6: "wallet", 7: "compass", 8: "calendar", 9: "smile", 10: "shield",
};

export function Icon({ name, size = 18, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg
      className={className ? `icon ${className}` : "icon"}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}

// A round gold-edged badge holding an icon (cards, area tiles).
export function IconBadge({ name, size = 16 }: { name: IconName; size?: number }) {
  return (
    <span className="icon-badge" aria-hidden="true">
      <Icon name={name} size={size} />
    </span>
  );
}

// The badge for a life area, or nothing if the area isn't known.
export function AreaBadge({ order, size }: { order: number | null | undefined; size?: number }) {
  const name = order ? AREA_ICONS[order] : undefined;
  return name ? <IconBadge name={name} size={size} /> : null;
}
